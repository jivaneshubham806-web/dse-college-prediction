/**
 * Strict verified lookup by Institute_Code.
 * Uses trimmed code as the key.
 */
export function getCollegeLocation(code: string): { city: string; district: string } | null {
  if (!code) return null;
  const cleanCode = code.trim();
  const entry = MASTER_COLLEGE_LOCATIONS[cleanCode];
  if (!entry) return null;
  return {
    city: entry.city,
    district: entry.district,
  };
}

export const getVerifiedLocation = getCollegeLocation;

export function getCollegeDistrict(code: string, name: string): string {
  if (code && MASTER_COLLEGE_LOCATIONS[code.trim()]) {
    return MASTER_COLLEGE_LOCATIONS[code.trim()].district;
  }
  const lowerName = (name || '').toLowerCase();
  for (const city of COMMON_CITIES) {
    if (lowerName.includes(city.toLowerCase())) {
      return city;
    }
  }
  if (code && code.length >= 1 && DTE_REGION_FALLBACK[code[0]]) {
    return DTE_REGION_FALLBACK[code[0]];
  }
  return 'Maharashtra';
}

/**
 * Cleans location text by removing brackets and text within brackets.
 */
function cleanLocationText(text: string): string {
  if (!text) return '';
  return text
    .replace(/\([^)]*\)/g, '')
    .replace(/\[[^\]]*\]/g, '')
    .replace(/[()\[\]]/g, '')
    .trim();
}

/**
 * Builds a location list for each college from getCollegeLocation(code):
 * - The district (removing text in brackets)
 * - Each part of the city string after splitting on "/" and removing text in brackets.
 * Example: city "Parli / Beed (Beed)" gives parts "Parli" and "Beed"; district "Beed" is also added.
 */
export function getCollegeLocationParts(code: string): string[] {
  if (!code) return [];
  const loc = getCollegeLocation(code);
  const partsSet = new Set<string>();

  if (loc) {
    if (loc.city) {
      const cleanCity = cleanLocationText(loc.city);
      const chunks = cleanCity.split('/');
      for (const chunk of chunks) {
        const trimmed = chunk.trim();
        if (trimmed.length > 0) {
          partsSet.add(trimmed);
        }
      }
    }
    if (loc.district) {
      const cleanDist = cleanLocationText(loc.district);
      if (cleanDist.length > 0) {
        partsSet.add(cleanDist);
      }
    }
  }

  return Array.from(partsSet);
}

/**
 * Checks if a college matches a single selected city (case-insensitive, trimmed).
 * A college matches if the selected value equals any of its parts or its district.
 */
export function collegeMatchesCity(code: string, selectedCity: string): boolean {
  if (!selectedCity) return true;
  const target = selectedCity.trim().toLowerCase();
  if (!target) return true;
  const parts = getCollegeLocationParts(code);
  return parts.some((p) => p.trim().toLowerCase() === target);
}

/**
 * Checks if a college matches any of the selected cities.
 * If no city is selected (selectedCities is empty), returns true (no filter).
 * Matches if any selected city equals any of its parts or its district (case-insensitive, trimmed).
 */
export function collegeMatchesCities(code: string, selectedCities: string[]): boolean {
  if (!selectedCities || selectedCities.length === 0) {
    return true;
  }
  const parts = getCollegeLocationParts(code).map((p) => p.trim().toLowerCase());
  if (parts.length === 0) {
    return false;
  }
  return selectedCities.some((city) => {
    const target = city.trim().toLowerCase();
    return target.length > 0 && parts.includes(target);
  });
}

/**
 * Builds the city dropdown from every distinct part and district across all 363 colleges,
 * so each option returns at least one college.
 */
export function getAllCityOptions(): string[] {
  const map = new Map<string, string>();

  for (const code of Object.keys(MASTER_COLLEGE_LOCATIONS)) {
    const parts = getCollegeLocationParts(code);
    for (const part of parts) {
      const key = part.toLowerCase();
      if (!map.has(key)) {
        map.set(key, part);
      } else {
        const existing = map.get(key)!;
        if (existing === existing.toUpperCase() && part !== part.toUpperCase()) {
          map.set(key, part);
        }
      }
    }
  }

  return Array.from(map.values()).sort((a, b) => a.localeCompare(b));
}

